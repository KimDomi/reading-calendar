import Holidays from 'date-holidays';
import {writeFileSync} from 'node:fs';
const calendar = new Holidays('KR');
const dates = {};
const day = 86400000;
const format = time => new Date(time).toISOString().slice(0,10);
for (let year = 2020; year <= 2050; year++) {
  for (const holiday of calendar.getHolidays(year).filter(h => h.type === 'public')) {
    // date-holidays 3.38.0 anchors the Seollal P3D span on New Year's Day.
    // Korean public holidays span the preceding day through the following day.
    const correction = holiday.name === '설날' && !holiday.substitute ? -day : 0;
    for (let time = holiday.start.getTime() + correction; time < holiday.end.getTime() + correction; time += day) {
      // The package returns instants in Korea's time zone; format the local date.
      const date = format(time + 9 * 3600000);
      dates[date] = [...new Set([...(dates[date] || []), holiday.name])];
    }
  }
}
// Separately proclaimed public holidays/election days absent from recurring rules.
const extra = {
  '2020-04-15':'국회의원 선거일', '2020-08-17':'임시공휴일',
  '2022-03-09':'대통령 선거일', '2022-06-01':'전국동시지방선거일',
  '2023-10-02':'임시공휴일', '2024-04-10':'국회의원 선거일',
  '2025-01-27':'임시공휴일', '2025-06-03':'대통령 선거일',
  '2026-06-03':'전국동시지방선거일',
};
for (const [date,name] of Object.entries(extra)) dates[date] = [name];
writeFileSync('dist/holidays.js', '// Generated by scripts-holidays.mjs; Korea public holidays 2020–2050.\nexport const holidays = '+JSON.stringify(Object.fromEntries(Object.entries(dates).sort()))+';\n');
